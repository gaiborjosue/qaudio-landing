// Renders the site's logo (public/qaudio-logo.svg) as the PNG the story
// designer hands the image model as its brand reference, and writes it to
// public/qaudio-logo.png and agent/lib/brand-logo.ts (as a data URL, so the
// agent needs no file or site address at runtime). Run it again after the
// logo changes: node scripts/brand-logo.mjs
import { readFileSync, writeFileSync } from "node:fs"
import sharp from "sharp"

const svg = readFileSync("public/qaudio-logo.svg")
// Black on white with a margin, so the model reads the mark itself, not a
// transparent cut-out it might fill with any colour.
const logo = await sharp(svg, { density: 300 })
  .resize({ height: 900 })
  .png()
  .toBuffer()
const { width, height } = await sharp(logo).metadata()
const png = await sharp({
  create: {
    width: width + 160,
    height: height + 160,
    channels: 3,
    background: "#ffffff",
  },
})
  .composite([{ input: logo, top: 80, left: 80 }])
  .png({ compressionLevel: 9, palette: true, colours: 16 })
  .toBuffer()

writeFileSync("public/qaudio-logo.png", png)
writeFileSync(
  "agent/lib/brand-logo.ts",
  `// Generated by scripts/brand-logo.mjs from public/qaudio-logo.svg; don't edit.
// The Q Audio logo as a PNG data URL: the story designer's brand reference.
export const BRAND_LOGO_PNG =
  "data:image/png;base64,${png.toString("base64")}"
`
)
console.log(`Logo: ${width + 160}×${height + 160}, ${png.length} bytes.`)
